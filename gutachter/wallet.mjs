// Generates the Gutachter's two preprod wallets (buyer payer, seller payTo) the way the
// x402-express template does, appends them to ../.local/secrets.env (mode 600, read by scripts/env-split.mjs) once,
// and prints ONLY the addresses. A wallet already in ../.env or ../.local/secrets.env is reused; ../.env is never written.
import {readFileSync,appendFileSync,existsSync,mkdirSync,chmodSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {parseEnv} from 'node:util';
import {Address,PrivateKey} from '@evolution-sdk/evolution';
import {addressFromSeed} from '@evolution-sdk/evolution/sdk/wallet/Derivation';

const envPath=fileURLToPath(new URL('../.env',import.meta.url));
const secretsPath=fileURLToPath(new URL('../.local/secrets.env',import.meta.url));
const addressOf=mnemonic=>Address.toBech32(addressFromSeed(mnemonic,{networkId:0}).address);

const read=path=>existsSync(path)?readFileSync(path,'utf8'):'';
const secrets=read(secretsPath),env={...parseEnv(read(envPath)),...parseEnv(secrets)};
const lines=[];
const ensure=(key,make)=>{
 if(env[key]) return env[key];
 const value=make();
 lines.push(`${key}="${value}"`);
 return value;
};
const buyerMnemonic=ensure('GUTACHTER_BUYER_MNEMONIC',()=>PrivateKey.generateMnemonic());
const buyerAddress=ensure('GUTACHTER_BUYER_ADDRESS',()=>addressOf(buyerMnemonic));
const sellerMnemonic=ensure('GUTACHTER_SELLER_MNEMONIC',()=>PrivateKey.generateMnemonic());
const sellerAddress=ensure('GUTACHTER_SELLER_ADDRESS',()=>addressOf(sellerMnemonic));
if(addressOf(buyerMnemonic)!==buyerAddress||addressOf(sellerMnemonic)!==sellerAddress) throw new Error('A GUTACHTER_*_ADDRESS in .env or .local/secrets.env does not match its mnemonic');
if(lines.length){
 mkdirSync(fileURLToPath(new URL('../.local',import.meta.url)),{recursive:true,mode:0o700});
 appendFileSync(secretsPath,(!secrets||secrets.endsWith('\n')?'':'\n')+'# gutachter (x402) wallets, generated by gutachter/wallet.mjs\n'+lines.join('\n')+'\n',{mode:0o600});
 chmodSync(secretsPath,0o600);
}
console.log(`buyer  (payer, fund this): ${buyerAddress}`);
console.log(`seller (payTo):            ${sellerAddress}`);
console.log(lines.length?`appended ${lines.length} line(s) to .local/secrets.env`:'both wallets already exist, nothing written');
